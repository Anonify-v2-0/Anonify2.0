const NEXT_STEPS: Record<Mode, string[]> = {
  local: [
    "docker compose up -d      # Postgres + MinIO, with the bucket created",
    "pnpm db:migrate           # apply the schema",
    "pnpm ocr:warm             # fetch the ~5 MB OCR model now, not mid-redaction",
    "pnpm dev                  # http://localhost:3000",
  ],
  demo: [
    "Fill in DATABASE_URL, BLOB_READ_WRITE_TOKEN and MISTRAL_API_KEY in .env",
    "pnpm db:migrate           # apply the schema to your Neon database",
    "pnpm dev                  # http://localhost:3000",
  ],
}

async function main(): Promise<void> {
  const rl = createInterface({ input: process.stdin, output: process.stdout })

  try {
    console.log(`
  Anonify setup

  How would you like to run Anonify?

    1. Fully local          (recommended for development)
       Postgres and MinIO through Docker Compose, Tesseract for OCR.
       No accounts, no API keys, nothing leaves your machine.

    2. Demo-compatible
       The same services as the deployed demo: Neon, Vercel Blob and
       Mistral OCR. You provide your own keys.
`)

    const answer = (await rl.question("  Choose 1 or 2 [1]: ")).trim()
    const mode: Mode = answer === "2" ? "demo" : "local"

    if (existsSync(ENV_PATH)) {
      const existing = await readFile(ENV_PATH, "utf8")
      const hasValues = existing
        .split("\n")
        .some((line) => /^[A-Z_]+=.+/.test(line.trim()))

      if (hasValues) {
        console.log("\n  A .env already exists and has values in it.")
        const overwrite = (
          await rl.question("  Overwrite it? Existing secrets will be lost. [y/N]: ")
        )
          .trim()
          .toLowerCase()

        if (overwrite !== "y" && overwrite !== "yes") {
          console.log("\n  Left .env alone. Nothing was changed.\n")
          return
        }

        // Keep a copy: ENCRYPTION_KEY is not recoverable, and documents sealed
        // with the old one cannot be read without it.
        await writeFile(`${ENV_PATH}.backup`, existing, "utf8")
        console.log("  Previous .env copied to .env.backup")
      }
    }

    await writeFile(ENV_PATH, mode === "local" ? localEnv() : demoEnv(), "utf8")

    console.log(`
  Wrote .env for the ${mode === "local" ? "fully local" : "demo-compatible"} setup.
`)

    if (mode === "demo") {
      console.log("  Still needed — the script cannot generate these:\n")
      console.log("    DATABASE_URL           a Neon connection string")
      console.log("    BLOB_READ_WRITE_TOKEN  a Vercel Blob token")
      console.log("    MISTRAL_API_KEY        for OCR (or use OCR_PROVIDER=tesseract)\n")
    }

    console.log("  Next:\n")
    for (const step of NEXT_STEPS[mode]) console.log(`    ${step}`)
    console.log("\n  See README.md for the full walkthrough.\n")
  } finally {
    rl.close()
  }
}

main().catch((error: unknown) => {
  console.error(`\n  ${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 1
})

/**
 * Interactive setup.
 *
 *   pnpm setup
 *
 * Writes a working `.env` for one of two ways of running Anonify, and says
 * plainly which values still need a key. The alternative — a list of
 * environment variables in a README and a runtime failure when one is missing —
 * is how a fresh clone becomes an afternoon.
 *
 * Nothing here is required: `.env.example` documents every variable, and this
 * script only saves people from discovering them one error at a time.
 */

import { randomBytes } from "node:crypto"
import { existsSync } from "node:fs"
import { readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import { createInterface } from "node:readline/promises"

const ENV_PATH = path.join(process.cwd(), ".env")

type Mode = "local" | "demo"

/** 32 bytes of hex — what the crypto and identity layers expect. */
function secret(): string {
  return randomBytes(32).toString("hex")
}

type EnvLines = { key: string; value: string; comment?: string }[]

function render(title: string, groups: { heading: string; lines: EnvLines }[]): string {
  const out: string[] = [
    `# ${title}`,
    "# Generated by `pnpm setup`. Safe to edit by hand.",
    "",
  ]

  for (const group of groups) {
    out.push(`# ---- ${group.heading} ${"-".repeat(Math.max(0, 60 - group.heading.length))}`)
    for (const line of group.lines) {
      if (line.comment) out.push(`# ${line.comment}`)
      out.push(`${line.key}=${line.value}`)
    }
    out.push("")
  }

  return out.join("\n")
}


/**
 * Shapes shared by the corpus generator, the checker and (later) the scorer.
 * The label file format is documented in benchmarks/README.md; change both
 * together.
 */

export const CATEGORIES = [
  "person",
  "address",
  "phone",
  "email",
  "government-id",
  "bank-account",
  "financial",
  "date-of-birth",
  "customer-id",
  "confidential",
  "api-key",
  "url",
  "other",
] as const

export type Category = (typeof CATEGORIES)[number]

export function isCategory(value: string): value is Category {
  return (CATEGORIES as readonly string[]).includes(value)
}

export const LOCALES = [
  "en-US",
  "en-GB",
  "de-DE",
  "fr-FR",
  "es-ES",
  "en-IN",
] as const

export type Locale = (typeof LOCALES)[number]

export type Split = "dev" | "test"
export type LengthBucket = "short" | "medium" | "long"
export type Density = "none" | "low" | "medium" | "high"
export type RenderFormat = "txt" | "eml" | "pdf" | "docx" | "csv" | "xlsx"

export type CastSpec = { id: string; role: string; mentions: number }

/** Everything the script decides about a document before any model sees it. */
export type DocumentSpec = {
  id: string
  index: number
  split: Split
  docType: string
  /** The type as the prompt describes it: "support email thread, 4 messages". */
  docTypeDetail: string
  locale: Locale
  length: LengthBucket
  targetWords: number
  density: Density
  cast: CastSpec[]
  mustInclude: Category[]
  negatives: string[]
  render: RenderFormat[]
}

/** What the model is asked to return. */
export type ModelDocument = {
  title: string
  docType: string
  locale: string
  cast: { id: string; name: string }[]
  body: string
  negatives: string[]
}

export type Span = {
  start: number
  end: number
  category: Category
  value: string
  /** The cast member this value belongs to, when it can be told. */
  entity?: string
  /** Set when the value was generated by the script rather than written. */
  placeholder?: string
}

export type Negative = { start: number; end: number; value: string }

export type LabelledDocument = {
  id: string
  split: Split
  title: string
  docType: string
  docTypeDetail: string
  locale: Locale
  length: LengthBucket
  density: Density
  render: RenderFormat[]
  words: number
  text: string
  spans: Span[]
  negatives: Negative[]
  entities: {
    id: string
    name: string
    role: string
    requested: number
    mentions: number
  }[]
  spec: { mustInclude: Category[]; negatives: string[]; targetWords: number }
  generator: {
    backend: string
    model: string
    promptVersion: string
    seed: number
    attempt: number
    /** Brace-for-bracket slips and bare placeholders fixed; see repairMarkup. */
    markupRepairs: number
    reviewedByHuman: boolean
  }
}
